# どの表示言語でも固定する文言
FIXED_LABELS = {
    'source_label': 'From',
    'target_label': 'To',
    'target_label_short': 'To',
}


def get_ui_labels(lang):
    """指定言語のUIラベル。足りないキーは English で補完する"""
    labels = dict(UI_LABELS['English'])
    labels.update(UI_LABELS.get(lang, {}))
    labels.update(FIXED_LABELS)
    return labels
